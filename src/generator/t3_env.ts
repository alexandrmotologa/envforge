import { ParityMatrixRow, InferredType } from '../types/index.js';

export interface T3EnvGeneratorOptions {
  framework?: 'core' | 'nextjs';
  clientPrefix?: string;
}

export function generateT3EnvSchema(
  rows: ParityMatrixRow[],
  options: T3EnvGeneratorOptions = { framework: 'core' }
): string {
  const clientPrefix = options.clientPrefix || detectClientPrefix(rows) || 'NEXT_PUBLIC_';
  const serverRows: ParityMatrixRow[] = [];
  const clientRows: ParityMatrixRow[] = [];

  for (const row of rows) {
    if (isClientKey(row.key, clientPrefix)) {
      clientRows.push(row);
    } else {
      serverRows.push(row);
    }
  }

  const serverFields = serverRows.map((row) => renderZodField(row));
  const clientFields = clientRows.map((row) => renderZodField(row));

  const pkg = options.framework === 'nextjs' ? '@t3-oss/env-nextjs' : '@t3-oss/env-core';

  const lines = [
    `// Generated by EnvForge`,
    `import { createEnv } from '${pkg}';`,
    `import { z } from 'zod';`,
    ``,
    `export const env = createEnv({`,
    `  server: {`,
    ...serverFields.map((f) => `    ${f}`),
    `  },`,
    `  clientPrefix: '${clientPrefix}',`,
    `  client: {`,
    ...clientFields.map((f) => `    ${f}`),
    `  },`,
    `  runtimeEnv: process.env,`,
    `  emptyStringAsUndefined: true,`,
    `});`,
  ];

  return lines.join('\n') + '\n';
}

function isClientKey(key: string, prefix: string): boolean {
  if (key.startsWith(prefix)) return true;
  const commonPrefixes = ['NEXT_PUBLIC_', 'VITE_', 'PUBLIC_', 'EXPO_PUBLIC_', 'GATSBY_', 'NUXT_PUBLIC_'];
  return commonPrefixes.some((p) => key.startsWith(p));
}

function detectClientPrefix(rows: ParityMatrixRow[]): string | null {
  for (const row of rows) {
    if (row.key.startsWith('VITE_')) return 'VITE_';
    if (row.key.startsWith('NEXT_PUBLIC_')) return 'NEXT_PUBLIC_';
    if (row.key.startsWith('EXPO_PUBLIC_')) return 'EXPO_PUBLIC_';
    if (row.key.startsWith('PUBLIC_')) return 'PUBLIC_';
  }
  return null;
}

function renderZodField(row: ParityMatrixRow): string {
  const isOptional = Object.values(row.environments).some((cell) => cell.status === 'MISSING');
  let validator = mapTypeToZod(row.inferredType, row.suggestedDefault, !!row.secretFinding);

  if (isOptional && !row.suggestedDefault) {
    validator += '.optional()';
  }

  return `${row.key}: ${validator},`;
}

function mapTypeToZod(type: InferredType, defaultValue?: string, isSecret?: boolean): string {
  if (isSecret) {
    return 'z.string().min(1)';
  }

  switch (type) {
    case 'port': {
      let rule = 'z.coerce.number().int().min(1).max(65535)';
      if (defaultValue && !isNaN(Number(defaultValue))) {
        rule += `.default(${defaultValue})`;
      }
      return rule;
    }
    case 'number': {
      let rule = 'z.coerce.number()';
      if (defaultValue && !isNaN(Number(defaultValue))) {
        rule += `.default(${defaultValue})`;
      }
      return rule;
    }
    case 'boolean': {
      let rule = 'z.coerce.boolean()';
      if (defaultValue !== undefined) {
        const boolVal = defaultValue.toLowerCase() === 'true' || defaultValue === '1' || defaultValue === 'yes';
        rule += `.default(${boolVal})`;
      }
      return rule;
    }
    case 'url': {
      return 'z.string().url()';
    }
    case 'email': {
      return 'z.string().email()';
    }
    case 'uuid': {
      return 'z.string().uuid()';
    }
    case 'json': {
      return 'z.string().transform((val) => JSON.parse(val))';
    }
    case 'enum':
    case 'string':
    default: {
      let rule = 'z.string()';
      if (defaultValue) {
        rule += `.default(${JSON.stringify(defaultValue)})`;
      }
      return rule;
    }
  }
}
