import { ParityMatrixRow, InferredType } from '../types/index.js';

export interface ZodGeneratorOptions {
  includeValidationHelper?: boolean;
  exportType?: boolean;
}

export function generateZodSchema(
  rows: ParityMatrixRow[],
  options: ZodGeneratorOptions = { includeValidationHelper: true, exportType: true }
): string {
  const schemaLines: string[] = [];

  for (const row of rows) {
    const key = row.key;
    const type = row.inferredType;
    const def = row.suggestedDefault;
    const isOptional = Object.values(row.environments).some((cell) => cell.status === 'MISSING');

    let validator = mapTypeToZod(type, def);

    if (isOptional && !def) {
      validator += '.optional()';
    }

    if (row.description) {
      const comment = row.description.replace(/\r?\n/g, ' ');
      schemaLines.push(`  /** ${comment} */`);
    }

    schemaLines.push(`  ${key}: ${validator},`);
  }

  const lines = [
    `// Generated by EnvForge`,
    `import { z } from 'zod';`,
    ``,
    `export const envSchema = z.object({`,
    ...schemaLines,
    `});`,
  ];

  if (options.exportType) {
    lines.push(``, `export type Env = z.infer<typeof envSchema>;`);
  }

  if (options.includeValidationHelper) {
    lines.push(
      ``,
      `export function validateEnv(runtimeEnv: Record<string, string | undefined> = process.env): Env {`,
      `  const result = envSchema.safeParse(runtimeEnv);`,
      `  if (!result.success) {`,
      `    console.error('Environment variable validation failed:', JSON.stringify(result.error.format(), null, 2));`,
      `    throw new Error('Invalid environment variables configuration');`,
      `  }`,
      `  return result.data;`,
      `}`,
      ``,
      `export const env = validateEnv();`
    );
  }

  return lines.join('\n') + '\n';
}

function mapTypeToZod(type: InferredType, defaultValue?: string): string {
  switch (type) {
    case 'port': {
      let rule = 'z.coerce.number().int().min(1).max(65535)';
      if (defaultValue && !isNaN(Number(defaultValue))) {
        rule += `.default(${defaultValue})`;
      }
      return rule;
    }
    case 'number': {
      let rule = 'z.coerce.number()';
      if (defaultValue && !isNaN(Number(defaultValue))) {
        rule += `.default(${defaultValue})`;
      }
      return rule;
    }
    case 'boolean': {
      let rule = 'z.coerce.boolean()';
      if (defaultValue !== undefined) {
        const boolVal = defaultValue.toLowerCase() === 'true' || defaultValue === '1' || defaultValue === 'yes';
        rule += `.default(${boolVal})`;
      }
      return rule;
    }
    case 'url': {
      return 'z.string().url()';
    }
    case 'email': {
      return 'z.string().email()';
    }
    case 'uuid': {
      return 'z.string().uuid()';
    }
    case 'json': {
      return 'z.string().transform((val) => JSON.parse(val))';
    }
    case 'string':
    default: {
      let rule = 'z.string().min(1)';
      if (defaultValue && !defaultValue.includes('\n')) {
        rule += `.default(${JSON.stringify(defaultValue)})`;
      }
      return rule;
    }
  }
}
