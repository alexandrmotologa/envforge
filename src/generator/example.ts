import { ParityMatrixRow } from '../types/index.js';

export function generateEnvExample(rows: ParityMatrixRow[]): string {
  const lines: string[] = [
    `# ========================================================`,
    `# Environment Configuration Template`,
    `# Auto-generated by EnvForge`,
    `# ========================================================`,
    ``,
  ];

  // Group by category prefix if common, or output alphabetical
  for (const row of rows) {
    if (row.description) {
      lines.push(`# ${row.description.replace(/\r?\n/g, ' ')}`);
    } else {
      lines.push(`# Type: ${row.inferredType}`);
    }

    let val = '';
    if (row.secretFinding) {
      val = `<your-${row.key.toLowerCase().replace(/_/g, '-')}>`;
    } else if (row.suggestedDefault !== undefined && row.suggestedDefault !== '') {
      val = row.suggestedDefault;
    } else {
      switch (row.inferredType) {
        case 'port':
          val = '3000';
          break;
        case 'boolean':
          val = 'false';
          break;
        case 'url':
          val = 'https://api.example.com';
          break;
        case 'email':
          val = 'admin@example.com';
          break;
        default:
          val = '';
      }
    }

    lines.push(`${row.key}=${val}`, ``);
  }

  return lines.join('\n');
}
