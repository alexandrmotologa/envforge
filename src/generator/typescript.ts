import { ParityMatrixRow } from '../types/index.js';

export function generateTypeScriptDeclarations(rows: ParityMatrixRow[]): string {
  const propertyLines: string[] = [];

  for (const row of rows) {
    if (row.description) {
      propertyLines.push(`      /** ${row.description.replace(/\r?\n/g, ' ')} */`);
    }
    // Environment variables in process.env are always strings at runtime
    propertyLines.push(`      ${row.key}?: string;`);
  }

  const lines = [
    `// Generated by EnvForge`,
    `/* eslint-disable */`,
    `declare global {`,
    `  namespace NodeJS {`,
    `    interface ProcessEnv {`,
    ...propertyLines,
    `    }`,
    `  }`,
    `}`,
    ``,
    `export {};`,
  ];

  return lines.join('\n') + '\n';
}
