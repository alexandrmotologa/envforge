import { ParityMatrixRow, InferredType } from '../types/index.js';

export interface ValibotGeneratorOptions {
  includeValidationHelper?: boolean;
  exportType?: boolean;
}

export function generateValibotSchema(
  rows: ParityMatrixRow[],
  options: ValibotGeneratorOptions = { includeValidationHelper: true, exportType: true }
): string {
  const schemaLines: string[] = [];

  for (const row of rows) {
    const key = row.key;
    const type = row.inferredType;
    const def = row.suggestedDefault;
    const isOptional = Object.values(row.environments).some((cell) => cell.status === 'MISSING');

    let validator = mapTypeToValibot(type, !!row.secretFinding);

    if (def !== undefined) {
      if (type === 'port' || type === 'number') {
        validator = `v.optional(${validator}, ${def})`;
      } else if (type === 'boolean') {
        const boolVal = def.toLowerCase() === 'true' || def === '1' || def === 'yes';
        validator = `v.optional(${validator}, ${boolVal})`;
      } else {
        validator = `v.optional(${validator}, ${JSON.stringify(def)})`;
      }
    } else if (isOptional) {
      validator = `v.optional(${validator})`;
    }

    if (row.description) {
      const comment = row.description.replace(/\r?\n/g, ' ');
      schemaLines.push(`  /** ${comment} */`);
    }

    schemaLines.push(`  ${key}: ${validator},`);
  }

  const lines = [
    `// Generated by EnvForge`,
    `import * as v from 'valibot';`,
    ``,
    `export const envSchema = v.object({`,
    ...schemaLines,
    `});`,
  ];

  if (options.exportType) {
    lines.push(``, `export type Env = v.InferOutput<typeof envSchema>;`);
  }

  if (options.includeValidationHelper) {
    lines.push(
      ``,
      `export function validateEnv(runtimeEnv: Record<string, string | undefined> = process.env): Env {`,
      `  return v.parse(envSchema, runtimeEnv);`,
      `}`,
      ``,
      `export const env = validateEnv();`
    );
  }

  return lines.join('\n') + '\n';
}

function mapTypeToValibot(type: InferredType, isSecret?: boolean): string {
  if (isSecret) {
    return `v.pipe(v.string(), v.nonEmpty('Secret cannot be empty'))`;
  }

  switch (type) {
    case 'port': {
      return `v.pipe(v.string(), v.transform((val) => Number(val)), v.integer(), v.minValue(1), v.maxValue(65535))`;
    }
    case 'number': {
      return `v.pipe(v.string(), v.transform((val) => Number(val)), v.number())`;
    }
    case 'boolean': {
      return `v.pipe(v.string(), v.transform((val) => val === 'true' || val === '1' || val === 'yes'))`;
    }
    case 'url': {
      return `v.pipe(v.string(), v.url())`;
    }
    case 'email': {
      return `v.pipe(v.string(), v.email())`;
    }
    case 'uuid': {
      return `v.pipe(v.string(), v.uuid())`;
    }
    case 'json': {
      return `v.pipe(v.string(), v.transform((val) => JSON.parse(val)))`;
    }
    case 'enum':
    case 'string':
    default: {
      return `v.string()`;
    }
  }
}
