import { ParityMatrixRow, InferredType } from '../types/index.js';

export interface PydanticGeneratorOptions {
  className?: string;
  envFile?: string;
}

export function generatePydanticSettings(
  rows: ParityMatrixRow[],
  options: PydanticGeneratorOptions = {}
): string {
  const className = options.className || 'Settings';
  const envFile = options.envFile || '.env';

  const imports = new Set<string>(['Field']);
  let hasOptional = false;
  let hasAny = false;

  const fieldLines: string[] = [];

  for (const row of rows) {
    const isMissing = Object.values(row.environments).some((cell) => cell.status === 'MISSING');
    const isOptional = isMissing && row.suggestedDefault === undefined;
    if (isOptional) hasOptional = true;

    const { pyType, fieldArgs, requiredImports } = mapTypeToPydantic(
      row.inferredType,
      row.suggestedDefault,
      isOptional,
      row.description,
      !!row.secretFinding
    );

    for (const imp of requiredImports) {
      if (imp === 'Optional' || imp === 'Any' || imp === 'Dict') {
        if (imp === 'Any') hasAny = true;
      } else {
        imports.add(imp);
      }
    }

    const typeAnnotation = isOptional ? `Optional[${pyType}]` : pyType;
    fieldLines.push(`    ${row.key}: ${typeAnnotation} = ${fieldArgs}`);
  }

  const typingImports: string[] = [];
  if (hasOptional) typingImports.push('Optional');
  if (hasAny) typingImports.push('Any', 'Dict');

  const pydanticImportsStr = Array.from(imports).sort().join(', ');

  const lines = [
    `# Generated by EnvForge`,
  ];

  if (typingImports.length > 0) {
    lines.push(`from typing import ${typingImports.join(', ')}`);
  }

  lines.push(
    `from pydantic import ${pydanticImportsStr}`,
    `from pydantic_settings import BaseSettings, SettingsConfigDict`,
    ``,
    `class ${className}(BaseSettings):`,
    `    model_config = SettingsConfigDict(`,
    `        env_file="${envFile}",`,
    `        env_file_encoding="utf-8",`,
    `        extra="ignore"`,
    `    )`,
    ``,
    ...fieldLines,
    ``,
    `settings = ${className}()`,
  );

  return lines.join('\n') + '\n';
}

interface PydanticFieldSpec {
  pyType: string;
  fieldArgs: string;
  requiredImports: string[];
}

function mapTypeToPydantic(
  type: InferredType,
  defaultValue?: string,
  isOptional?: boolean,
  description?: string,
  isSecret?: boolean
): PydanticFieldSpec {
  const descArg = description ? `description=${JSON.stringify(description)}` : '';

  if (isSecret) {
    const parts = [isOptional ? 'default=None' : '...'];
    if (descArg) parts.push(descArg);
    return {
      pyType: 'SecretStr',
      fieldArgs: `Field(${parts.join(', ')})`,
      requiredImports: ['SecretStr'],
    };
  }

  switch (type) {
    case 'port': {
      const def = defaultValue ? `default=${defaultValue}` : (isOptional ? 'default=None' : '...');
      const parts = [def, 'ge=1', 'le=65535'];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'int',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
    case 'number': {
      const def = defaultValue ? `default=${defaultValue}` : (isOptional ? 'default=None' : '...');
      const parts = [def];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'float',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
    case 'boolean': {
      let def = '...';
      if (defaultValue !== undefined) {
        const boolVal = defaultValue.toLowerCase() === 'true' || defaultValue === '1' || defaultValue === 'yes';
        def = `default=${boolVal ? 'True' : 'False'}`;
      } else if (isOptional) {
        def = 'default=None';
      }
      const parts = [def];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'bool',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
    case 'url': {
      const parts = [defaultValue ? `default=${JSON.stringify(defaultValue)}` : (isOptional ? 'default=None' : '...')];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'str',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
    case 'email': {
      const parts = [defaultValue ? `default=${JSON.stringify(defaultValue)}` : (isOptional ? 'default=None' : '...')];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'str',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
    case 'json': {
      const parts = [isOptional ? 'default=None' : '...'];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'Dict[str, Any]',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: ['Dict', 'Any'],
      };
    }
    case 'enum':
    case 'uuid':
    case 'string':
    default: {
      const parts = [defaultValue ? `default=${JSON.stringify(defaultValue)}` : (isOptional ? 'default=None' : '...')];
      if (descArg) parts.push(descArg);
      return {
        pyType: 'str',
        fieldArgs: `Field(${parts.join(', ')})`,
        requiredImports: [],
      };
    }
  }
}
